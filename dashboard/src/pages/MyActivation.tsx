import React, { useEffect, useState } from 'react';
import { AnimatePresence, motion } from 'framer-motion';
import { Check, CheckCircle2, Copy, Download as DownloadIcon, KeyRound, Laptop, LogOut, Monitor, Plus, Timer, Zap } from 'lucide-react';
import { SectionHeader } from '../components/SectionHeader';
import { api } from '../services/api';
import { ActivationTokenCreated, AuthorizedDevice, ConnectedComputer, DistributionInfo, Entitlement } from '../types';
import { NavTab } from '../components/Sidebar';
import { ACCESS_STATES } from '../utils/format';
import { isWindowsVisitor } from '../utils/platform';

/**
 * Activation code = "ASA1." + base64url(JSON {u: server URL, t: single-use activation token}).
 * Decoded by extension/src/shared/config.ts parseActivationCode(). It can only be generated by a
 * signed-in account, works once, expires after 30 minutes and binds one browser's key to that account.
 */
export function makeActivationCode(serverUrl: string, token: string): string {
  const json = JSON.stringify({ u: serverUrl.trim().replace(/\/$/, ''), t: token });
  const b64 = btoa(unescape(encodeURIComponent(json)));
  return 'ASA1.' + b64.replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

/** Server times are UTC; some databases return them without a timezone suffix. */
const parseUtc = (value: string) => new Date(/[zZ]|[+-]\d\d:?\d\d$/.test(value) ? value : value + 'Z');
const formatDate = (value?: string) => (value ? parseUtc(value).toLocaleString() : '—');

const STATUS_CLASS: Record<string, string> = {
  ACTIVE: 'status-active',
  PENDING: 'status-pending',
  REVOKED: 'status-revoked',
};

export const MyActivation: React.FC<{ email: string; entitlement?: Entitlement | null; onNavigate?: (tab: NavTab) => void }> = ({
  email,
  entitlement,
  onNavigate,
}) => {
  // FREE_PAUSED browsers stay connected (prompt checks pause), so codes can still be created
  const licensed = !entitlement || ACCESS_STATES.includes(entitlement.state);
  const [created, setCreated] = useState<ActivationTokenCreated | null>(null);
  const [devices, setDevices] = useState<AuthorizedDevice[]>([]);
  const [error, setError] = useState('');
  const [copied, setCopied] = useState(false);
  const [busy, setBusy] = useState(false);
  const [now, setNow] = useState(Date.now());
  const [computers, setComputers] = useState<ConnectedComputer[]>([]);
  const [info, setInfo] = useState<DistributionInfo | null>(null);
  // "Connect this PC" was clicked: the code was handed to the AgentShield app through agentshield://
  const [pcLinkSent, setPcLinkSent] = useState(false);
  const [downloading, setDownloading] = useState(false);

  const loadDevices = () => {
    api.getMyDevices().then(setDevices).catch((e) => setError(e.message));
    api.getMyComputers().then(setComputers).catch(() => undefined);
  };

  useEffect(() => {
    loadDevices();
    api.getDistributionInfo().then(setInfo).catch(() => setInfo(null));
    const t = setInterval(() => setNow(Date.now()), 1000);
    // Follow the PC connection while this page is open (the app connects the browsers within a minute)
    const poll = setInterval(loadDevices, 10000);
    return () => {
      clearInterval(t);
      clearInterval(poll);
    };
  }, []);

  /** One click: a fresh code goes straight to the AgentShield Windows app, which asks before connecting. */
  const connectThisPc = async () => {
    setError('');
    setBusy(true);
    try {
      const token = await api.createActivationToken();
      setCreated(token);
      setCopied(false);
      setPcLinkSent(true);
      window.location.href = `agentshield://connect?code=${encodeURIComponent(makeActivationCode(token.api_url, token.token))}`;
    } catch (e: any) {
      setError(e.message);
    } finally {
      setBusy(false);
    }
  };

  const downloadSetup = async () => {
    setError('');
    setDownloading(true);
    try {
      await api.downloadFile('AgentShield-System-Setup.exe');
    } catch (e: any) {
      setError(e.message || 'Could not start the download.');
    } finally {
      setTimeout(() => setDownloading(false), 1500);
    }
  };

  const removePc = async (pc: ConnectedComputer) => {
    if (!window.confirm(`Remove ${pc.name || 'this PC'}? All its browsers are signed out and AI tools are blocked there until the PC is connected again.`)) return;
    try {
      await api.revokeMyComputer(pc.id);
      loadDevices();
    } catch (e: any) {
      setError(e.message);
    }
  };

  const code = created ? makeActivationCode(created.api_url, created.token) : '';
  const secondsLeft = created ? Math.max(0, Math.floor((parseUtc(created.expires_at).getTime() - now) / 1000)) : 0;
  const expired = Boolean(created) && secondsLeft === 0;

  const generate = async () => {
    setError('');
    setBusy(true);
    try {
      setCreated(await api.createActivationToken());
      setCopied(false);
    } catch (e: any) {
      setError(e.message);
    } finally {
      setBusy(false);
    }
  };

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(code);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  };

  const revoke = async (d: AuthorizedDevice) => {
    if (!window.confirm('Sign out this browser? AI tools will be blocked there until it is activated again.')) return;
    try {
      await api.revokeMyDevice(d.id);
      loadDevices();
    } catch (e: any) {
      setError(e.message);
    }
  };

  // Browsers of a connected PC are listed under that PC
  const liveDevices = devices.filter((d) => d.status !== 'REVOKED' && !d.computer_id);
  const setupAvailable = Boolean(info?.downloads?.system_setup);

  // One way first, matching the visitor's computer: the Windows app on Windows (when published),
  // the extension and an activation code elsewhere. The other way stays under "Other ways to connect".
  const windowsFirst = isWindowsVisitor() && setupAvailable;
  const windowsWay = (
    <>
  {/* Windows: one setup and one click for every browser on the PC */}
  <section className="glass-panel" style={{ padding: '24px' }}>
    <SectionHeader icon={<Zap size={18} />} title="Windows: connect every browser on this PC at once" right={<span className="chip">Recommended</span>}>
      AgentShield for Windows adds the extension to Chrome, Edge and Brave and connects all of them with one click.
      The PC uses one device of your plan, however many browsers it has.
    </SectionHeader>
    <ol className="steps" style={{ marginLeft: 18 }}>
      <li>
        <strong>Install AgentShield for Windows</strong> (once per PC; Windows asks for permission).{' '}
        {setupAvailable ? (
          <button type="button" className="link-btn" disabled={downloading || !licensed} onClick={downloadSetup}>
            {downloading ? 'Starting download...' : 'Download AgentShield-System-Setup.exe'}
          </button>
        ) : (
          <span className="cell-sub">The Windows setup is not published on this server yet.</span>
        )}
      </li>
      <li>
        <strong>Connect this PC:</strong> click the button below, then <strong>Open AgentShield</strong> and <strong>Connect</strong>.
        Every browser on the PC connects by itself within a minute.
      </li>
    </ol>
    <div style={{ display: 'flex', gap: 10, flexWrap: 'wrap', marginTop: 14 }}>
      <button type="button" className="btn-primary" onClick={connectThisPc} disabled={busy || !licensed}>
        <Laptop size={16} /> Connect this PC
      </button>
      {setupAvailable && (
        <button type="button" className="btn-secondary" onClick={downloadSetup} disabled={downloading || !licensed}>
          <DownloadIcon size={15} /> Download for Windows
        </button>
      )}
    </div>
    {pcLinkSent && created && !expired && (
      <div className="callout" style={{ marginTop: 14, display: 'block' }}>
        Your browser should ask to <strong>open AgentShield</strong>. Nothing happened? Install AgentShield for Windows first,
        or open <strong>Connect AgentShield</strong> from the Start menu and paste the code shown below.
      </div>
    )}

    {computers.length > 0 && (
      <div className="table-wrap" style={{ marginTop: 16 }}>
        <table className="data-table">
          <thead>
            <tr>
              <th>PC</th>
              <th>Browsers</th>
              <th>Connected</th>
              <th>Last seen</th>
              <th />
            </tr>
          </thead>
          <tbody>
            {computers.map((pc) => (
              <tr key={pc.id}>
                <td>
                  <div style={{ fontWeight: 600, color: 'var(--text-main)' }}>{pc.name || 'PC'}</div>
                  <div className="cell-sub">{pc.platform || 'Windows'}</div>
                </td>
                <td>
                  {pc.browsers.length === 0 ? (
                    <span className="cell-sub">Waiting for browsers to connect…</span>
                  ) : (
                    pc.browsers.map((b) => (
                      <div key={b.id} className="cell-sub" style={{ color: 'var(--text-main)' }}>
                        {b.browser || 'Browser'}{b.status === 'PENDING' ? ' (waiting for approval)' : ''}
                      </div>
                    ))
                  )}
                </td>
                <td>{formatDate(pc.created_at)}</td>
                <td>{formatDate(pc.last_seen_at)}</td>
                <td style={{ textAlign: 'right' }}>
                  <button type="button" className="btn-ghost-danger" onClick={() => removePc(pc)}>
                    <LogOut size={14} /> Remove PC
                  </button>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    )}
  </section>
    </>
  );
  const codeWay = (
    <>
  <section className="glass-panel" style={{ padding: '24px' }}>
    <SectionHeader icon={<KeyRound size={18} />} title="Activation code">
      For one browser (any computer), or to paste into the AgentShield app on Windows. Paste it into the AgentShield
      extension to connect that browser to your account ({email}). A code works once and expires after 30 minutes.
      Do not share it: whoever uses it first connects to your account. Generating a new code cancels the previous one.
    </SectionHeader>

    {licensed && (entitlement?.state === 'FREE_ACTIVE' || entitlement?.state === 'FREE_PAUSED') && (
      <div className="cell-sub" style={{ marginBottom: 10 }}>
        Free plan · {entitlement.devices_used} of {entitlement.device_limit} device{entitlement.device_limit === 1 ? '' : 's'} in use (a PC with the Windows app counts once)
        {entitlement.state === 'FREE_PAUSED' ? ' · prompt checks paused until the monthly reset' : ''}
      </div>
    )}
    {licensed && entitlement?.expires_at && (
      <div className="cell-sub" style={{ marginBottom: 10 }}>
        {entitlement.state === 'TRIAL_ACTIVE' ? 'Free trial' : 'Plan'} active until {formatDate(entitlement.expires_at)} ·{' '}
        {entitlement.devices_used} of {entitlement.device_limit} devices in use
      </div>
    )}
    <button type="button" className="btn-primary" onClick={generate} disabled={busy || !licensed}>
      <Plus size={16} /> {created ? 'Generate a new code' : 'Generate activation code'}
    </button>
    {error && <div style={{ marginTop: '10px', fontSize: '12.5px', color: 'var(--color-danger-text)' }}>{error}</div>}

    <AnimatePresence>
      {created && (
        <motion.div
          initial={{ opacity: 0, y: -6 }}
          animate={{ opacity: 1, y: 0 }}
          exit={{ opacity: 0 }}
          transition={{ duration: 0.2 }}
        >
          <div className="code-ready" style={expired ? { background: 'var(--bg-subtle)', borderColor: 'var(--border-subtle)' } : undefined}>
            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', gap: '12px', marginBottom: '12px' }}>
              <div style={{ display: 'flex', gap: '10px', alignItems: 'center' }}>
                {expired ? <Timer size={20} color="var(--text-muted)" /> : <CheckCircle2 size={20} color="var(--color-success)" />}
                <div>
                  <div style={{ fontSize: '14px', fontWeight: 700, color: 'var(--text-main)' }}>
                    {expired ? 'This code has expired' : 'Your activation code'}
                  </div>
                  <div style={{ fontSize: '12.5px', color: 'var(--text-muted)' }}>
                    {expired
                      ? 'Generate a new one.'
                      : `Expires in ${Math.floor(secondsLeft / 60)}:${String(secondsLeft % 60).padStart(2, '0')}. Shown only once.`}
                  </div>
                </div>
              </div>
            </div>

            {!expired && (
              <>
                <div className="code-box">
                  <code>{code}</code>
                  <button type="button" className="btn-primary" onClick={copy}>
                    {copied ? <Check size={14} /> : <Copy size={14} />} {copied ? 'Copied' : 'Copy code'}
                  </button>
                </div>
                <ol className="steps">
                  <li>In Chrome or Edge, click the <strong>AgentShield</strong> icon in the toolbar (or open <strong>Connect AgentShield</strong> on Windows).</li>
                  <li>Paste this code and click <strong>Connect and verify</strong> (in the Windows app: <strong>Connect</strong>).</li>
                  <li>The browser (or every browser on the PC) is connected to <strong>{email}</strong> and AI tools unlock.</li>
                </ol>
              </>
            )}
          </div>
        </motion.div>
      )}
    </AnimatePresence>
  </section>
    </>
  );

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: '20px' }}>
      <div>
        <h1 className="page-title">My activation</h1>
        <p className="page-subtitle">Connect AgentShield to your account. AI tools stay blocked in a browser until it is connected.</p>
      </div>

  {!licensed && (
    <div className="callout callout-warning" style={{ marginBottom: 12 }}>
      <span>
      {entitlement?.state === 'NONE'
          ? 'No active plan yet. Start the free trial, choose a plan or buy credits first (if Account & plan asks, confirm your email).'
          : entitlement?.state === 'EXPIRED'
          ? 'Your plan has ended. Renew it or buy credits to connect browsers again.'
          : entitlement?.state === 'NO_CREDITS'
          ? 'Your credits are used up. Buy credits or choose a plan to connect browsers again.'
          : entitlement?.state === 'LIMIT_REACHED'
          ? 'This month\'s included prompt checks are used up. Buy credits or upgrade to continue.'
          : entitlement?.state === 'CAP_REACHED'
          ? 'Your monthly usage limit is reached. Raise it in Usage & credits to continue.'
          : 'Your access is suspended. Contact support.'}{' '}
        {onNavigate && <button type="button" className="link-btn" onClick={() => onNavigate('account')}>Account &amp; plan</button>}
      </span>
    </div>
  )}

      {windowsFirst ? windowsWay : codeWay}

      <details className="disclosure other-ways" open={windowsFirst ? Boolean(created) : computers.length > 0}>
        <summary>{windowsFirst ? 'Other ways to connect: one browser with an activation code' : 'Other ways to connect: AgentShield for Windows (every browser on a PC)'}</summary>
        {windowsFirst ? codeWay : windowsWay}
      </details>

      <section className="glass-panel" style={{ padding: '24px' }}>
        <SectionHeader icon={<Monitor size={18} />} title="My browsers">
          Browsers connected with a code, each using one device of your plan. Sign one out if you no longer use it or it was lost.
          Browsers connected through the Windows app are listed under their PC above.
        </SectionHeader>
        <div className="table-wrap">
          <table className="data-table">
            <thead>
              <tr>
                <th>Browser</th>
                <th>Activated</th>
                <th>Last seen</th>
                <th>Status</th>
                <th />
              </tr>
            </thead>
            <tbody>
              {liveDevices.length === 0 && (
                <tr>
                  <td colSpan={5} className="empty-cell">
                    <Monitor size={22} color="var(--text-faint)" />
                    <div>No activated browsers yet.</div>
                  </td>
                </tr>
              )}
              {liveDevices.map((d) => (
                <tr key={d.id}>
                  <td>
                    <div style={{ fontWeight: 600, color: 'var(--text-main)' }}>{d.browser || 'Browser'}</div>
                    <div className="cell-sub">{d.platform || ''}</div>
                  </td>
                  <td>{formatDate(d.created_at)}</td>
                  <td>{formatDate(d.last_seen_at)}</td>
                  <td>
                    <span className={`status-pill ${STATUS_CLASS[d.status]}`}>
                      <span className="status-dot" /> {d.status === 'PENDING' ? 'Waiting for approval' : 'Active'}
                    </span>
                  </td>
                  <td style={{ textAlign: 'right' }}>
                    <button type="button" className="btn-ghost-danger" onClick={() => revoke(d)}>
                      <LogOut size={14} /> Sign out
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>
    </div>
  );
};
