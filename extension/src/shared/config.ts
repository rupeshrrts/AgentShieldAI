/// <reference types="chrome" />
/**
 * AgentShield Extension Configuration
 *
 * The server address is read, in order of precedence, from:
 * 1. Enterprise policy (chrome.storage.managed: apiUrl, dashboardUrl), pushed by Group Policy / Intune.
 * 2. client-config.json next to manifest.json, written by the installer.
 * 3. The activation code the user pasted (it contains the server address).
 *
 * None of these grants access. A browser is authorized only after a signed-in account
 * activates it (see background/auth-state.ts and shared/device-identity.ts). Older
 * "deviceKey" / "enrollmentCode" settings are ignored.
 *
 * An activation code is "ASA1." + base64url(JSON {u: apiUrl, t: activation token}),
 * generated by the dashboard (My activation). The token is single-use and only valid
 * together with the account's email and password.
 */
import { ClientConfig } from './types';

export const DEFAULT_API_BASE_URL = 'http://localhost:8000';
export const EXTENSION_VERSION = chrome.runtime.getManifest().version;
export const ACTIVATION_PREFIX = 'ASA1.';

export interface ActivationCode {
  apiUrl: string;
  token: string;
}

function clean(value: unknown): string | undefined {
  return typeof value === 'string' && value.trim() !== '' ? value.trim() : undefined;
}

/** Decodes an activation code. Returns null if it is malformed. */
export function parseActivationCode(code: string): ActivationCode | null {
  try {
    // Tolerate copy/paste noise: whitespace and line breaks anywhere, surrounding quotes
    const trimmed = (code || '').replace(/\s+/g, '').replace(/^["'`]+|["'`,]+$/g, '');
    if (!trimmed.startsWith(ACTIVATION_PREFIX)) return null;
    const b64 = trimmed.slice(ACTIVATION_PREFIX.length).replace(/-/g, '+').replace(/_/g, '/');
    const padded = b64 + '='.repeat((4 - (b64.length % 4)) % 4);
    const json = JSON.parse(decodeURIComponent(escape(atob(padded))));
    const apiUrl = clean(json.u)?.replace(/\/$/, '');
    const token = clean(json.t);
    if (!apiUrl || !/^https?:\/\//i.test(apiUrl) || !token || !token.startsWith('asa_')) return null;
    return { apiUrl, token };
  } catch {
    return null;
  }
}

function normalize(raw: any): ClientConfig {
  if (!raw || typeof raw !== 'object') return {};
  return {
    apiUrl: clean(raw.apiUrl)?.replace(/\/$/, ''),
    dashboardUrl: clean(raw.dashboardUrl)?.replace(/\/$/, ''),
  };
}

async function readManagedConfig(): Promise<ClientConfig> {
  try {
    if (chrome.storage?.managed) {
      return normalize(await chrome.storage.managed.get(null));
    }
  } catch {
    // No enterprise policy configured
  }
  return {};
}

async function readClientConfigFile(): Promise<ClientConfig> {
  try {
    const res = await fetch(chrome.runtime.getURL('client-config.json'));
    if (res.ok) return normalize(await res.json());
  } catch {
    // client-config.json is optional
  }
  return {};
}

function merge(...layers: ClientConfig[]): ClientConfig {
  const out: ClientConfig = {};
  for (const layer of layers) {
    for (const [k, v] of Object.entries(layer)) {
      if (v !== undefined) (out as any)[k] = v;
    }
  }
  return out;
}

/** Resolves the server address set by IT (policy > installer file), if any. */
export async function loadClientConfig(): Promise<ClientConfig> {
  const [managed, file] = await Promise.all([readManagedConfig(), readClientConfigFile()]);
  return merge(file, managed);
}

/** True when IT fixed the server address, so a pasted code cannot point the browser elsewhere. */
export function serverLockedByAdmin(config: ClientConfig): boolean {
  return Boolean(config.apiUrl);
}
